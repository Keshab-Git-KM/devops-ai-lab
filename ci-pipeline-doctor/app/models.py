"""Pydantic models shared across the API, analyzers, and GitHub layer."""

from __future__ import annotations

from collections import Counter
from enum import Enum

from pydantic import BaseModel, Field, computed_field


class Severity(str, Enum):
    critical = "critical"
    high = "high"
    medium = "medium"
    low = "low"
    info = "info"


# Ordering used when ranking issues (higher = more important).
_SEVERITY_RANK = {
    Severity.critical: 4,
    Severity.high: 3,
    Severity.medium: 2,
    Severity.low: 1,
    Severity.info: 0,
}


def severity_rank(sev: Severity) -> int:
    return _SEVERITY_RANK[sev]


class FixCommand(BaseModel):
    """A copy-paste-ready snippet the user can run or drop into a file."""

    label: str = Field("Run this", description="What the snippet does.")
    language: str = Field("bash", description="Syntax highlighting hint (bash, json, yaml…).")
    code: str = Field(..., description="The exact command/snippet, ready to copy.")


class DetectedIssue(BaseModel):
    """A single problem detected in the build logs, with an actionable fix."""

    category: str = Field(..., description="Machine-friendly category id, e.g. 'dependency'.")
    title: str = Field(..., description="Short human-readable title.")
    severity: Severity = Severity.medium
    confidence: float = Field(0.5, ge=0.0, le=1.0)

    root_cause: str = Field(..., description="One-line why the build failed.")
    explanation: str = Field("", description="Deeper context: what is actually happening and why.")
    suggested_fix: str = Field(..., description="One-line summary of the fix.")
    fix_steps: list[str] = Field(default_factory=list, description="Ordered, concrete steps.")
    commands: list[FixCommand] = Field(default_factory=list, description="Copy-paste snippets.")

    evidence: list[str] = Field(default_factory=list, description="Relevant log lines.")
    docs_url: str | None = None


class AnalyzeRequest(BaseModel):
    logs: str = Field(..., min_length=1, description="Raw CI/build log text.")
    context: dict = Field(default_factory=dict, description="Optional metadata (repo, job, etc.).")


class AnalysisResult(BaseModel):
    """The full diagnosis returned for a set of logs."""

    summary: str
    issues: list[DetectedIssue] = Field(default_factory=list)
    provider: str = "heuristic"
    detected_platform: str | None = Field(None, description="Guessed CI platform, if recognizable.")
    log_line_count: int = 0

    @property
    def primary_issue(self) -> DetectedIssue | None:
        return self.issues[0] if self.issues else None

    @computed_field  # serialized into the API response
    @property
    def severity_counts(self) -> dict[str, int]:
        counts = Counter(i.severity.value for i in self.issues)
        return {s.value: counts.get(s.value, 0) for s in Severity if counts.get(s.value)}

    def to_markdown(self) -> str:
        """Render the diagnosis as a Markdown comment (for PRs / chat)."""
        lines = ["## 🩺 CI Pipeline Doctor", "", f"_{self.summary}_"]
        if self.detected_platform:
            lines.append(f"\n**Detected platform:** {self.detected_platform}")
        lines.append("")
        if not self.issues:
            lines.append("No known failure patterns matched. Review the raw logs manually.")
            return "\n".join(lines)

        for i, issue in enumerate(self.issues, 1):
            badge = f"`{issue.severity.value}` · {int(issue.confidence * 100)}% confidence"
            lines += [f"### {i}. {issue.title}  \n{badge}", ""]
            lines += [f"**Root cause:** {issue.root_cause}", ""]
            if issue.explanation:
                lines += [f"**What's happening:** {issue.explanation}", ""]
            lines += [f"**Fix:** {issue.suggested_fix}", ""]
            if issue.fix_steps:
                lines.append("**Steps:**")
                lines += [f"{n}. {step}" for n, step in enumerate(issue.fix_steps, 1)]
                lines.append("")
            for cmd in issue.commands:
                lines += [f"_{cmd.label}_", f"```{cmd.language}", cmd.code, "```", ""]
            if issue.evidence:
                snippet = "\n".join(issue.evidence[:5])
                lines += ["<details><summary>Evidence</summary>", "", "```", snippet, "```", "</details>", ""]
            if issue.docs_url:
                lines += [f"📚 {issue.docs_url}", ""]
        lines.append("<sub>Generated by AI CI/CD Pipeline Doctor</sub>")
        return "\n".join(lines)
